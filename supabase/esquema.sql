-- ---------- Socios con acceso (tú y Dianelly) ----------
create table public.miembros (
  user_id uuid primary key references auth.users (id) on delete cascade,
  nombre  text not null
);

create or replace function public.es_miembro()
returns boolean
language sql stable security definer set search_path = public
as $$
  select exists (select 1 from public.miembros where user_id = auth.uid());
$$;

create or replace function public.mi_nombre()
returns text
language sql stable security definer set search_path = public
as $$
  select nombre from public.miembros where user_id = auth.uid();
$$;

-- ---------- Tablas ----------
create table public.productos (
  id            bigint generated by default as identity primary key,
  nombre        text not null check (length(trim(nombre)) > 0),
  categoria     text not null default 'Otro',
  precio_compra numeric(10,2) not null check (precio_compra >= 0),
  precio_venta  numeric(10,2) not null check (precio_venta >= 0),
  stock         integer not null default 0 check (stock >= 0),
  stock_minimo  integer not null default 2 check (stock_minimo >= 0),
  creado        timestamptz not null default now()
);

create table public.ventas (
  id       bigint generated by default as identity primary key,
  fecha    timestamptz not null default now(),
  total    numeric(12,2) not null default 0,
  ganancia numeric(12,2) not null default 0,
  vendedor text
);
create index ventas_fecha_idx on public.ventas (fecha);

create table public.venta_items (
  id              bigint generated by default as identity primary key,
  venta_id        bigint not null references public.ventas (id) on delete cascade,
  producto_id     bigint references public.productos (id) on delete set null,
  nombre          text not null,
  categoria       text not null,
  cantidad        integer not null check (cantidad > 0),
  precio_compra_u numeric(10,2) not null,
  precio_venta_u  numeric(10,2) not null
);
create index venta_items_venta_idx on public.venta_items (venta_id);

create table public.entradas (
  id             bigint generated by default as identity primary key,
  fecha          timestamptz not null default now(),
  producto_id    bigint references public.productos (id) on delete set null,
  nombre         text not null,
  cantidad       integer not null check (cantidad > 0),
  costo_u        numeric(10,2) not null check (costo_u >= 0),
  nota           text,
  registrado_por text
);
create index entradas_fecha_idx on public.entradas (fecha);

-- ---------- Seguridad: solo los miembros ven y modifican ----------
alter table public.miembros    enable row level security;
alter table public.productos   enable row level security;
alter table public.ventas      enable row level security;
alter table public.venta_items enable row level security;
alter table public.entradas    enable row level security;

create policy miembros_leer on public.miembros for select to authenticated using (public.es_miembro());

create policy productos_leer     on public.productos for select to authenticated using (public.es_miembro());
create policy productos_crear    on public.productos for insert to authenticated with check (public.es_miembro());
create policy productos_editar   on public.productos for update to authenticated using (public.es_miembro()) with check (public.es_miembro());
create policy productos_eliminar on public.productos for delete to authenticated using (public.es_miembro());

-- Ventas y entradas solo se leen directo; se escriben con las funciones de abajo
-- para que el stock siempre cuadre.
create policy ventas_leer   on public.ventas      for select to authenticated using (public.es_miembro());
create policy items_leer    on public.venta_items for select to authenticated using (public.es_miembro());
create policy entradas_leer on public.entradas    for select to authenticated using (public.es_miembro());

-- ---------- Operaciones ----------

-- Registra una venta con uno o varios productos y descuenta el stock.
-- items: [{"producto_id": 1, "cantidad": 2, "precio_venta_u": 350}]  (precio opcional)
create or replace function public.registrar_venta(items jsonb)
returns bigint
language plpgsql security definer set search_path = public
as $$
declare
  v_id     bigint;
  it       jsonb;
  p        public.productos%rowtype;
  v_cant   integer;
  v_precio numeric(10,2);
  v_total  numeric(12,2) := 0;
  v_gan    numeric(12,2) := 0;
begin
  if not public.es_miembro() then
    raise exception 'No autorizado';
  end if;
  if items is null or jsonb_typeof(items) <> 'array' or jsonb_array_length(items) = 0 then
    raise exception 'La venta no tiene productos';
  end if;

  insert into public.ventas (vendedor) values (public.mi_nombre()) returning id into v_id;

  for it in select * from jsonb_array_elements(items) loop
    v_cant := (it ->> 'cantidad')::integer;
    if v_cant is null or v_cant <= 0 then
      raise exception 'Cantidad inválida';
    end if;

    select * into p from public.productos where id = (it ->> 'producto_id')::bigint for update;
    if not found then
      raise exception 'Uno de los productos ya no existe';
    end if;
    if p.stock < v_cant then
      raise exception 'Stock insuficiente de "%": solo hay %', p.nombre, p.stock;
    end if;

    v_precio := coalesce((it ->> 'precio_venta_u')::numeric, p.precio_venta);
    if v_precio < 0 then
      raise exception 'Precio inválido';
    end if;

    update public.productos set stock = stock - v_cant where id = p.id;
    insert into public.venta_items (venta_id, producto_id, nombre, categoria, cantidad, precio_compra_u, precio_venta_u)
    values (v_id, p.id, p.nombre, p.categoria, v_cant, p.precio_compra, v_precio);

    v_total := v_total + v_precio * v_cant;
    v_gan   := v_gan + (v_precio - p.precio_compra) * v_cant;
  end loop;

  update public.ventas set total = v_total, ganancia = v_gan where id = v_id;
  return v_id;
end;
$$;

-- Elimina una venta y regresa las piezas al inventario.
create or replace function public.eliminar_venta(p_id bigint)
returns void
language plpgsql security definer set search_path = public
as $$
begin
  if not public.es_miembro() then
    raise exception 'No autorizado';
  end if;
  update public.productos p
     set stock = p.stock + vi.cantidad
    from public.venta_items vi
   where vi.venta_id = p_id and vi.producto_id = p.id;
  delete from public.ventas where id = p_id;
end;
$$;

-- Registra mercancía que llegó: suma al stock y actualiza el costo del producto.
create or replace function public.registrar_entrada(p_producto_id bigint, p_cantidad integer, p_costo_u numeric, p_nota text default null)
returns bigint
language plpgsql security definer set search_path = public
as $$
declare
  p    public.productos%rowtype;
  v_id bigint;
begin
  if not public.es_miembro() then
    raise exception 'No autorizado';
  end if;
  if p_cantidad is null or p_cantidad <= 0 then
    raise exception 'La cantidad debe ser mayor a 0';
  end if;
  if p_costo_u is null or p_costo_u < 0 then
    raise exception 'Costo inválido';
  end if;

  select * into p from public.productos where id = p_producto_id for update;
  if not found then
    raise exception 'El producto ya no existe';
  end if;

  update public.productos set stock = stock + p_cantidad, precio_compra = p_costo_u where id = p.id;
  insert into public.entradas (producto_id, nombre, cantidad, costo_u, nota, registrado_por)
  values (p.id, p.nombre, p_cantidad, p_costo_u, nullif(trim(p_nota), ''), public.mi_nombre())
  returning id into v_id;
  return v_id;
end;
$$;

-- Deshace una entrada (por si se capturó mal). No deja el stock en negativo.
create or replace function public.eliminar_entrada(p_id bigint)
returns void
language plpgsql security definer set search_path = public
as $$
declare
  e public.entradas%rowtype;
  v_stock integer;
begin
  if not public.es_miembro() then
    raise exception 'No autorizado';
  end if;
  select * into e from public.entradas where id = p_id;
  if not found then
    return;
  end if;
  if e.producto_id is not null then
    select stock into v_stock from public.productos where id = e.producto_id for update;
    if v_stock < e.cantidad then
      raise exception 'No se puede deshacer: de "%" ya se vendieron piezas de esa entrada (stock actual %)', e.nombre, v_stock;
    end if;
    update public.productos set stock = stock - e.cantidad where id = e.producto_id;
  end if;
  delete from public.entradas where id = p_id;
end;
$$;

-- ---------- Permisos de las funciones ----------
revoke execute on function public.es_miembro()                                   from public, anon;
revoke execute on function public.mi_nombre()                                    from public, anon;
revoke execute on function public.registrar_venta(jsonb)                         from public, anon;
revoke execute on function public.eliminar_venta(bigint)                         from public, anon;
revoke execute on function public.registrar_entrada(bigint, integer, numeric, text) from public, anon;
revoke execute on function public.eliminar_entrada(bigint)                       from public, anon;

grant execute on function public.es_miembro()                                    to authenticated;
grant execute on function public.mi_nombre()                                     to authenticated;
grant execute on function public.registrar_venta(jsonb)                          to authenticated;
grant execute on function public.eliminar_venta(bigint)                          to authenticated;
grant execute on function public.registrar_entrada(bigint, integer, numeric, text) to authenticated;
grant execute on function public.eliminar_entrada(bigint)                        to authenticated;
